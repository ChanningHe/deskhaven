//! Renders the merged catalog as the Rust data module `generated.rs` of
//! `deskhaven_core::strategies::catalog`, which declares it `#[rustfmt::skip]`: this layout is
//! the canonical one, so `--check` stays stable.

use std::fmt::Write as _;

use super::overlay::{Catalog, Entry, Kind, Text};

/// Rust identifier of a group name (`"security"` -> `Security`).
fn group_variant(group: &str) -> String {
    let mut chars = group.chars();
    match chars.next() {
        Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
        None => String::new(),
    }
}

/// A Rust string literal of `s` (Debug escapes quotes, backslashes and control characters).
fn lit(s: &str) -> String {
    format!("{s:?}")
}

fn text(t: &Text) -> String {
    format!("Text {{ en: {}, zh: {} }}", lit(&t.en), lit(&t.zh))
}

fn opt_i64(v: Option<i64>) -> String {
    v.map_or_else(|| "None".to_owned(), |n| format!("Some({n})"))
}

fn kind(kind: &Kind) -> String {
    match kind {
        Kind::Bool => "OptionKind::Bool".to_owned(),
        Kind::Text => "OptionKind::Text".to_owned(),
        Kind::Number { min, max } => format!(
            "OptionKind::Number {{ min: {}, max: {} }}",
            opt_i64(*min),
            opt_i64(*max)
        ),
        Kind::Choice(choices) => {
            let mut out = "OptionKind::Choice(&[\n".to_owned();
            for c in choices {
                let label = Text {
                    en: c.en.clone(),
                    zh: c.zh.clone(),
                };
                let _ = writeln!(
                    out,
                    "            Choice {{ value: {}, label: {} }},",
                    lit(&c.value),
                    text(&label)
                );
            }
            out.push_str("        ])");
            out
        }
    }
}

fn entry(out: &mut String, e: &Entry) {
    let default = e
        .default
        .as_deref()
        .map_or_else(|| "None".to_owned(), |d| format!("Some({})", lit(d)));
    let _ = write!(
        out,
        "    CatalogOption {{\n        key: {key},\n        kind: {kind},\n        group: Group::{group},\n        default: {default},\n        secret: {secret},\n        label: {label},\n        description: {description},\n    }},\n",
        key = lit(&e.key),
        kind = kind(&e.kind),
        group = group_variant(&e.group),
        secret = e.secret,
        label = text(&e.label),
        description = text(&e.description),
    );
}

/// The whole `generated.rs`.
pub fn render(catalog: &Catalog) -> String {
    let mut out = String::new();
    out.push_str("// @generated by `cargo xtask gen-strategy-catalog`. Do not edit: change\n");
    out.push_str("// overlay.toml (or the client source) and regenerate.\n");
    out.push_str(
        "//\n// Keys and boolean defaults: rustdesk/rustdesk `libs/base/src/config/keys.rs`\n",
    );
    out.push_str(
        "// (`KEYS_SETTINGS`) and rustdesk/hbb_common `src/config.rs` (`keys`, `option2bool`).\n\n",
    );
    out.push_str("use super::{CatalogOption, Choice, Group, OptionKind, Revisions, Text};\n\n");
    let _ = writeln!(
        out,
        "pub(super) const SOURCE: Revisions = Revisions {{\n    rustdesk: {},\n    hbb_common: {},\n}};\n",
        lit(&catalog.source.rustdesk),
        lit(&catalog.source.hbb_common)
    );
    out.push_str("pub(super) const OPTIONS: &[CatalogOption] = &[\n");
    for e in &catalog.entries {
        entry(&mut out, e);
    }
    out.push_str("];\n");
    out
}

#[cfg(test)]
mod tests {
    use super::super::overlay::{Choice, Revisions};
    use super::*;

    fn t(en: &str, zh: &str) -> Text {
        Text {
            en: en.to_owned(),
            zh: zh.to_owned(),
        }
    }

    #[test]
    fn renders_a_marked_module_with_escaped_literals() {
        let catalog = Catalog {
            source: Revisions {
                rustdesk: "r1".to_owned(),
                hbb_common: "h1".to_owned(),
            },
            entries: vec![
                Entry {
                    key: "approve-mode".to_owned(),
                    kind: Kind::Choice(vec![Choice {
                        value: "click".to_owned(),
                        en: "Click".to_owned(),
                        zh: "点击".to_owned(),
                    }]),
                    group: "security".to_owned(),
                    default: None,
                    secret: false,
                    label: t("Say \"hi\"", "批准"),
                    description: t("a\\b", ""),
                },
                Entry {
                    key: "direct-access-port".to_owned(),
                    kind: Kind::Number {
                        min: Some(1),
                        max: None,
                    },
                    group: "network".to_owned(),
                    default: Some("21118".to_owned()),
                    secret: true,
                    label: t("Port", "端口"),
                    description: t("", ""),
                },
            ],
        };

        let out = render(&catalog);

        assert!(out.starts_with("// @generated"), "{out}");
        assert!(out.contains("rustdesk: \"r1\""));
        assert!(out.contains("key: \"approve-mode\""));
        assert!(
            out.contains(
                "Choice { value: \"click\", label: Text { en: \"Click\", zh: \"点击\" } },"
            )
        );
        assert!(out.contains("label: Text { en: \"Say \\\"hi\\\"\", zh: \"批准\" }"));
        assert!(out.contains("en: \"a\\\\b\""));
        assert!(out.contains("group: Group::Security,"));
        assert!(out.contains("kind: OptionKind::Number { min: Some(1), max: None },"));
        assert!(out.contains("default: Some(\"21118\"),"));
        assert!(out.contains("secret: true,"));
        assert!(out.ends_with("];\n"));
    }
}
