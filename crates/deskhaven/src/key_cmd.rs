//! `deskhaven key ...` subcommands and the key-material readiness check.

use std::io::Write;

use anyhow::Context;
use deskhaven_config::bootstrap::{Bootstrap, LoadOptions, Loaded};
use deskhaven_core::client_config::{ClientConfig, ConfigError, ConfigInput, HostSource};
use deskhaven_core::keys::{
    KeyWarning, SignalKeyPaths, master_key_path, read_master_key, read_signal_key,
};

use crate::config_cmd;

/// What `key show` prints. Only public data belongs here. Further lines come after the
/// key line, so `key show | head -n1` keeps yielding the key.
struct KeyReport {
    /// Base64 public key, the value clients put in their "Key" field.
    public_key: String,
    /// The RustDesk client configuration string (import box, `rustdesk --config`), when
    /// the ID server address is known (`public_url`). The relay is not part of it: the
    /// relay list lives in the database, which this command does not open.
    config_string: Option<String>,
    /// Why the configuration string could not be made, for a stderr warning. The key is
    /// the command's result; a failing extra never turns it into a failure.
    config_error: Option<ConfigError>,
}

impl KeyReport {
    fn new(config: &Bootstrap, public_key: String) -> Self {
        let resolved = ClientConfig::resolve(&ConfigInput {
            public_url: &config.public_url,
            request_host: None,
            signal_port: config.signal.port,
            relay_servers: &[],
            public_key: &public_key,
        });
        let (config_string, config_error) = match resolved.host_source {
            HostSource::Unknown => (None, None),
            _ => match resolved.server.config_string() {
                Ok(string) => (Some(string), None),
                Err(error) => (None, Some(error)),
            },
        };
        Self {
            public_key,
            config_string,
            config_error,
        }
    }

    /// The key line first, then the configuration string if there is one.
    fn write(&self, out: &mut impl Write) -> std::io::Result<()> {
        writeln!(out, "{}", self.public_key)?;
        self.config_string
            .iter()
            .try_for_each(|config| writeln!(out, "{config}"))
    }

    /// What is missing from the output and why (stderr).
    fn write_notes(&self, err: &mut impl Write) -> std::io::Result<()> {
        match (&self.config_string, self.config_error) {
            (_, Some(error)) => writeln!(
                err,
                "warning: client configuration string not printed: {error}"
            ),
            (None, None) => writeln!(
                err,
                "note: set public_url to also print the client configuration string"
            ),
            (Some(_), None) => Ok(()),
        }
    }
}

/// Prints the hbbs public key. Read-only: a missing key pair is an error,
/// keys are generated by the server on first start.
pub fn show(options: &LoadOptions) -> anyhow::Result<()> {
    let loaded = config_cmd::load_reporting(options)?;
    let paths = SignalKeyPaths::from_bootstrap(&loaded.config);
    let key = read_signal_key(&paths)
        .context("failed to read the hbbs key pair")?
        .with_context(|| {
            format!(
                "no hbbs key pair at {}; start the server once to generate it, \
                 or copy an existing hbbs id_ed25519 (and .pub) there",
                paths.secret().display()
            )
        })?;
    report_warnings(&key.warnings)?;
    let report = KeyReport::new(&loaded.config, key.value.public_key_base64());
    report.write(&mut std::io::stdout().lock())?;
    report.write_notes(&mut std::io::stderr().lock())?;
    Ok(())
}

/// `config check`: key material that exists must be valid; nothing is
/// generated. Also reminds to back up the master key (05-config §5).
pub fn check(loaded: &Loaded) -> anyhow::Result<()> {
    let config = &loaded.config;
    let master = read_master_key(&config.security.master_key, &config.data_dir)?;
    if let Some(master) = &master {
        report_warnings(&master.warnings)?;
    }
    if let Some(signal) = read_signal_key(&SignalKeyPaths::from_bootstrap(config))? {
        report_warnings(&signal.warnings)?;
    }
    let path = master_key_path(&config.data_dir);
    let location = if !config.security.master_key.is_empty() {
        "the security.master_key value".to_owned()
    } else if master.is_some() {
        path.display().to_string()
    } else {
        format!("{} (generated on first start)", path.display())
    };
    writeln!(
        std::io::stderr().lock(),
        "note: back up {location}; encrypted secrets cannot be recovered without it"
    )?;
    Ok(())
}

fn report_warnings(warnings: &[KeyWarning]) -> std::io::Result<()> {
    let mut err = std::io::stderr().lock();
    warnings
        .iter()
        .try_for_each(|warning| writeln!(err, "warning: {warning}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_failing_config_string_leaves_the_key_line_and_becomes_a_warning() {
        let report = KeyReport {
            public_key: "KEY".to_owned(),
            config_string: None,
            config_error: Some(ConfigError::NotAscii),
        };
        let (mut out, mut err) = (Vec::new(), Vec::new());

        report.write(&mut out).unwrap();
        report.write_notes(&mut err).unwrap();

        assert_eq!(String::from_utf8(out).unwrap(), "KEY\n");
        let err = String::from_utf8(err).unwrap();
        assert!(
            err.starts_with("warning:") && err.contains("ASCII"),
            "{err}"
        );
    }
}
